"""Builds the app's strings files (ADR 0028): each package/i18n/<lang>.json
becomes package/ui/strings-<lang>.js, which adds its table to
window.KWS_STRINGS. Stale strings-*.js files are removed.

The JSON files are what translators (and Weblate) edit; the .js files are
build output, ignored by git. Run by `just strings`, `just deploy-ui` and
tools/package.sh.

Usage: tools/strings.py [I18N_DIR [UI_DIR]]
"""
import json
import re
import sys
from pathlib import Path

LANG = re.compile(r"[A-Za-z]{2,3}([_-][A-Za-z0-9]{2,8})?")


def load(path):
    try:
        table = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        sys.exit(f"{path}: {e}")
    if not isinstance(table, dict) or not all(
        isinstance(k, str) and isinstance(v, str) for k, v in table.items()
    ):
        sys.exit(f"{path}: expected one object of text keys and text values")
    return table


def to_js(lang, table):
    body = json.dumps(table, ensure_ascii=False, indent=4)
    # JSON allows these two characters in strings; ES5 doesn't.
    body = body.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return (
        "/* Generated by tools/strings.py from package/i18n/"
        f"{lang}.json: edit that file. */\n"
        f'(window.KWS_STRINGS = window.KWS_STRINGS || {{}})["{lang}"] = {body};\n'
    )


def main():
    i18n = Path(sys.argv[1] if len(sys.argv) > 1 else "package/i18n")
    ui = Path(sys.argv[2] if len(sys.argv) > 2 else "package/ui")
    sources = sorted(i18n.glob("*.json"))
    english = load(i18n / "en.json")
    written = set()
    for path in sources:
        lang = path.stem
        if not LANG.fullmatch(lang):
            sys.exit(f"{path}: not a language name (en, de, pt_BR)")
        table = english if lang == "en" else load(path)
        extra = sorted(set(table) - set(english))
        if extra:
            print(f"warning: {path.name} has keys English doesn't: {', '.join(extra)}", file=sys.stderr)
        out = ui / f"strings-{lang}.js"
        text = to_js(lang, table)
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            out.write_text(text, encoding="utf-8")
        written.add(out.name)
    for old in ui.glob("strings-*.js"):
        if old.name not in written:
            old.unlink()
    print(f"strings: {', '.join(p.stem for p in sources)}")


if __name__ == "__main__":
    main()
